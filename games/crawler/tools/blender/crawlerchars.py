def run_pose(f, n, B, A=0.85, K=1.25, arm=0.7, bounce=0.06, lean=0.22, twist=0.18, arm_bend=0.9):
    """a run: long strides, knees folding high on the swing, arms pumping against the legs"""
    ph = TAU * f / n
    p = {}
    for side, o in (("L", 0.0), ("R", math.pi)):
        s = math.sin(ph + o)
        swing = max(0.0, math.sin(ph + o + 1.1))            # the knee folds as the leg comes through
        p["thigh" + side] = (-A * s - 0.1, 0, 0)
        p["shin" + side] = (K * swing + 0.15, 0, 0)
        p["foot" + side] = (-0.35 * swing + 0.25 * s, 0, 0)
    up = bounce * abs(math.cos(ph))
    p["hips"] = (lean * 0.3, twist * math.sin(ph), 0, 0, up, 0)
    p["spine"] = (lean * 0.4, -twist * 0.8 * math.sin(ph), 0)
    p["chest"] = (lean * 0.3, -twist * 0.6 * math.sin(ph), 0)
    p["head"] = (-lean * 0.9, twist * 1.2 * math.sin(ph), 0)
    for side, o in (("L", math.pi), ("R", 0.0)):
        s = math.sin(ph + o)
        p["uarm" + side] = (arm * s - 0.15, 0, 0)
        p["farm" + side] = (-arm_bend - 0.3 * max(0, -s), 0, 0)
    return p

def idle_pose(f, n, B, sway=1.0):
    ph = TAU * f / n
    b = math.sin(ph)
    p = {"hips": (0, 0, 0, 0, -0.008 * (1 - b) * 0.5, 0), "spine": (0.015 * b, 0, 0), "chest": (-0.035 * b * sway, 0, 0),
         "head": (0.02 * b, 0, 0)}
    for side, s in (("L", 1), ("R", -1)):
        p["uarm" + side] = (0.02 * b, 0, -s * 0.12 - s * 0.025 * b)
        p["farm" + side] = (-0.3, 0, 0)
        p["thigh" + side] = (-0.05, 0, s * 0.06)
        p["shin" + side] = (0.1, 0, 0)
        p["foot" + side] = (-0.05, 0, 0)
    return p

def stance(crouch=0.0, spread=0.08, stagger=0.0):
    p = {"hips": (0, 0, 0, 0, 0, 0)}
    for side, s in (("L", 1), ("R", -1)):
        st = stagger * s
        p["thigh" + side] = (-crouch - st, 0, s * spread)
        p["shin" + side] = (crouch * 1.8, 0, 0)
        p["foot" + side] = (-crouch * 0.8 + st, 0, 0)
    return p

def upper(p, lean=0.0, twist=0.0, drop=0.0, head=None):
    """the body above the hips: leaning forward (+) and turned (+ to the left)"""
    p["hips"] = (lean * 0.25, twist * 0.3, 0, 0, drop, 0)
    p["spine"] = (lean * 0.4, twist * 0.4, 0)
    p["chest"] = (lean * 0.35, twist * 0.4, 0)
    p["head"] = (-lean * 0.8 if head is None else head, -twist * 0.6, 0)
    return p

