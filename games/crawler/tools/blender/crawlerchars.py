def smoothstep(a, b, x):
    t = max(0.0, min(1.0, (x - a) / (b - a)))
    return t * t * (3 - 2 * t)

WHITE = (1.0, 1.0, 1.0)

# ───────────────────────── the humanoid ───────────────────────────────

class Body:
    """Proportions of a biped standing at the origin, facing -Y."""
    def __init__(self, hz, thigh, shin, torso, neck, arm_up, arm_lo, sx, hx):
        self.hz, self.thigh, self.shin, self.torso, self.neck = hz, thigh, shin, torso, neck
        self.arm_up, self.arm_lo, self.sx, self.hx = arm_up, arm_lo, sx, hx
        self.sz = hz + torso - 0.06                 # the shoulder joint's height
        self.ez = self.sz - arm_up                  # the elbow
        self.wz = self.ez - arm_lo                  # the wrist
        self.kz = hz - thigh                        # the knee
        self.nz = hz + torso                        # the base of the neck

def rig(M, B):
    M.bone("hips", None, (0, 0, B.hz - 0.05), (0, 0, B.hz + 0.1))
    M.bone("spine", "hips", (0, 0, B.hz + 0.1), (0, 0, B.hz + B.torso * 0.5))
    M.bone("chest", "spine", (0, 0, B.hz + B.torso * 0.5), (0, 0, B.nz))
    M.bone("head", "chest", (0, 0, B.nz), (0, 0, B.nz + B.neck))
    for s, side in ((1, "L"), (-1, "R")):
        M.bone("uarm" + side, "chest", (s * B.sx, 0, B.sz), (s * B.sx, 0, B.ez))
        M.bone("farm" + side, "uarm" + side, (s * B.sx, 0, B.ez), (s * B.sx, 0, B.wz))
        M.bone("hand" + side, "farm" + side, (s * B.sx, 0, B.wz), (s * B.sx, 0, B.wz - 0.1))
        M.bone("thigh" + side, "hips", (s * B.hx, 0, B.hz), (s * B.hx, 0, B.kz))
        M.bone("shin" + side, "thigh" + side, (s * B.hx, 0, B.kz), (s * B.hx, 0, 0.08))
        M.bone("foot" + side, "shin" + side, (s * B.hx, 0, 0.08), (s * B.hx, -0.18, 0.08))

def torso_w(B):
    hz = B.hz; t = B.torso
    return lambda p: {"hips": 1 - smoothstep(hz + 0.05, hz + t * 0.45, p.z),
                      "spine": smoothstep(hz + 0.05, hz + t * 0.45, p.z) * (1 - smoothstep(hz + t * 0.5, hz + t * 0.85, p.z)),
                      "chest": smoothstep(hz + t * 0.5, hz + t * 0.85, p.z)}

def skirt_w(B, side_split=0.04, amt=0.85):
    """a coat or robe below the hips: follows the hips at the top, each leg lower down"""
    def w(p):
        down = 1 - smoothstep(B.hz - 0.25, B.hz + 0.05, p.z)     # 0 at the waist, 1 below the upper thigh
        sL = smoothstep(-side_split, side_split, p.x)
        d = {"hips": 1 - down * amt + 1e-4}
        d["thighL"] = down * amt * sL + 1e-4
        d["thighR"] = down * amt * (1 - sL) + 1e-4
        return d
    return w

def limbs(M, B, c_uarm, c_farm, c_hand, c_thigh, c_shin, c_boot, r_arm=(0.07, 0.06, 0.055), r_leg=(0.1, 0.08, 0.06), boot=(0.13, 0.27, 0.14), seg=8, gloves=None, shin_boot=None):
    for s, side in ((1, "L"), (-1, "R")):
        x = s * B.sx
        M.limb("uarm" + side, (x, 0, B.sz + 0.02), (x, 0, B.ez), r_arm[0], r_arm[1], c_uarm, seg=seg)
        M.ell("farm" + side, (x, 0, B.ez), (r_arm[1] * 1.05, r_arm[1] * 1.05, r_arm[1] * 1.05), c_farm, seg=(seg, 5))
        M.limb("farm" + side, (x, 0, B.ez), (x, 0, B.wz + 0.02), r_arm[1], r_arm[2], c_farm, seg=seg)
        M.ell("hand" + side, (x, -0.01, B.wz - 0.05), (r_arm[2] * 1.15, r_arm[2] * 1.25, r_arm[2] * 1.4), c_hand, seg=(7, 5))
        hx = s * B.hx
        M.limb("thigh" + side, (hx, 0, B.hz + 0.02), (hx, 0, B.kz), r_leg[0], r_leg[1], c_thigh, seg=seg)
        M.ell("shin" + side, (hx, -0.01, B.kz), (r_leg[1] * 1.05, r_leg[1] * 1.1, r_leg[1] * 1.05), c_thigh, seg=(seg, 5))
        M.limb("shin" + side, (hx, 0, B.kz), (hx, 0, 0.1), r_leg[1], r_leg[2], c_shin, seg=seg)
        bw, bl, bh = boot
        M.box("foot" + side, (hx, -bl * 0.25, bh * 0.5), (bw, bl, bh), c_boot, bevel=0.03)
        if shin_boot:
            M.limb("shin" + side, (hx, 0, 0.08), (hx, 0, shin_boot[0]), r_leg[2] * 1.35, r_leg[2] * 1.3, c_boot, seg=seg)

