H = 1.2          # a wall's height (the camera looks straight down: low blocks, the tops carry the look)
CAPZ = 2.38      # where its cap course starts
D = 0.07         # how far the stone faces stand out of the mortar core

def root():
    M = Model()
    M.bone("root", None, (0, 0, 0), (0, 0, 1))
    return M

SIDES = [((1, 0, 0), (0, 1, 0)), ((-1, 0, 0), (0, -1, 0)), ((0, 1, 0), (-1, 0, 0)), ((0, -1, 0), (1, 0, 0))]   # (normal, along)

def pick(rng, cols):
    c = cols[rng.randrange(len(cols))]
    k = 0.9 + 0.2 * rng.random()
    return (c[0] * k, c[1] * k, c[2] * k)

# ───────────────────────── wall blocks ────────────────────────────────

def cap_layout(seed, rng):
    """four rectangles tiling the 2 x 2 top"""
    v = seed % 3
    if v == 0:
        a = (rng.random() - 0.5) * 0.6; b = (rng.random() - 0.5) * 0.6
        return [(-1, -1, a, b), (a, -1, 1, b), (-1, b, a, 1), (a, b, 1, 1)]
    if v == 1:
        cuts = [-1, -0.45 + rng.random() * 0.2, 0.05 + rng.random() * 0.15, 0.5 + rng.random() * 0.2, 1]
        return [(cuts[k], -1, cuts[k + 1], 1) for k in range(4)]
    b = 0.1 + rng.random() * 0.25
    c1 = -0.35 + rng.random() * 0.15; c2 = 0.3 + rng.random() * 0.15
    return [(-1, -1, 1, b), (-1, b, c1, 1), (c1, b, c2, 1), (c2, b, 1, 1)]

def ashlar_wall(seed, pal, courses=(0.0, 0.62, 1.22, 1.8, CAPZ), stones=2, cap_split=2, cap_h=0.22, cap_ch=0.07, jag=0.025, dent=0.03):
    """A block of dressed stone: a mortar core, on each side face courses of chamfered stones (their joints
    staggered from course to course, placed by the seed), and a cap of cap_split x cap_split stones on top."""
    rng = random.Random(seed)
    crng = random.Random(1000)                        # colours: the same for every variant (one topology, one colour set)
    M = root()
    e = 1 - D
    cuboid(M, "root", (-e, -e, 0), (e, e, CAPZ + 0.01), pal["mortar"], faces="xXyYZ", noise_amt=0.2)
    for sx in (-1, 1):            # mortar in the corner columns too, so no joint looks into an open stone back
        for sy in (-1, 1):
            x0, x1 = sorted((sx * e, sx * 0.995)); y0, y1 = sorted((sy * e, sy * 0.995))
            cuboid(M, "root", (x0, y0, 0), (x1, y1, CAPZ), pal["mortar"], faces=("X" if sx > 0 else "x") + ("Y" if sy > 0 else "y"), noise_amt=0.2)
    for si, (n, u) in enumerate(SIDES):
        n = Vector(n); u = Vector(u)
        for ci in range(len(courses) - 1):
            z0, z1 = courses[ci], courses[ci + 1]
            # joints along the face: evenly spread, staggered by course, nudged by the seed
            # the corners are bonded like quoins: on alternate courses the x faces or the y faces run to the corner,
            # the others stop at the core (no two stones fill the same corner, so no face hides inside another)
            full = (si >= 2) == (ci % 2 == 0)
            lo, hi = (-1.0, 1.0) if full else (-e, e)
            cuts = [lo]
            for k in range(1, stones):
                t = -1 + 2 * k / stones + (1 / stones if ci % 2 else 0) * 0.5 + (rng.random() - 0.5) * 0.35
                cuts.append(max(-0.75, min(0.75, t)))
            cuts.append(hi)
            cuts.sort()
            for k in range(stones):
                a, b = cuts[k], cuts[k + 1]
                c = n * e + u * ((a + b) / 2) + Vector((0, 0, (z0 + z1) / 2))
                low = ci == 0
                col = pick(crng, pal["stone"])
                if low and pal.get("damp"): col = mix(col, pal["damp"], 0.45 + 0.3 * crng.random())
                if crng.random() < pal.get("stain_p", 0.0): col = mix(col, pal["stain"], 0.4 + 0.3 * crng.random())
                d = D - rng.random() * 0.02
                j = [(rng.random() - 0.5) * jag for _ in range(4)]
                ch = 0.035 + rng.random() * 0.03
                v0 = len(M.v)
                pillow(M, "root", c, u, (0, 0, 1), n, (b - a) / 2, (z1 - z0) / 2, min(d, D - max(j) - 0.001), ch, col, jit=j, noise_amt=0.15)
                mark(M, v0, "side")
    # the cap: four cap stones over the whole top laid out a different way in each variant (two by two off
    # centre, four strips, one long slab and three), each a little domed or dished, edges bevelled
    for (x0, y0, x1, y1) in cap_layout(seed, rng):
        c = Vector(((x0 + x1) / 2, (y0 + y1) / 2, CAPZ))
        col = pick(crng, pal["cap"])
        j = [(rng.random() - 0.5) * jag for _ in range(4)]
        hh = cap_h - 0.012 - max(j)
        v0 = len(M.v)
        pillow(M, "root", c, (1, 0, 0), (0, 1, 0), (0, 0, 1), (x1 - x0) / 2, (y1 - y0) / 2, hh, cap_ch, col, jit=j, noise_amt=0.18,
               tri_top=(rng.random() - 0.6) * dent)
        mark(M, v0, "cap")
    return M

def mark(M, v0, kind):
    """remember which vertices make one piece of a block (for its stub)"""
    if not hasattr(M, "pieces"): M.pieces = []
    M.pieces.append((v0, len(M.v), kind))

def stub_positions(M, pos, seed=3, top=0.26):
    if getattr(M, "stub_mode", "") == "scale":
        # a rock: the whole lump squashed to a low broken stump, its top roughened
        out = []
        for p in pos:
            r = random.Random(hash((round(p.x, 2), round(p.y, 2), seed))).random()
            z = p.z * (top + 0.08) / H
            if p.z > H * 0.6: z += (r - 0.3) * 0.1
            out.append(Vector((p.x, p.y, max(0.0, z))))
        return out
    return _stub_pieces(M, pos, seed, top)

def _stub_pieces(M, pos, seed=3, top=0.26):
    """the same block broken off about 0.35 m up: the cap stones fallen onto the stump at odd heights and
    tilts (dark cracks between them), the stones of the upper courses crushed under them, the lowest course
    clipped to a ragged line"""
    rng = random.Random(seed)
    out = [p.copy() for p in pos]
    done = set()
    for (v0, v1, kind) in getattr(M, "pieces", []):
        done.update(range(v0, v1))
        if kind == "cap":
            ps = pos[v0:v1]
            cx = sum(p.x for p in ps) / len(ps); cy = sum(p.y for p in ps) / len(ps)
            zb = min(p.z for p in ps)
            h = top - 0.07 + rng.random() * 0.1
            tx = (rng.random() - 0.5) * 0.3; ty = (rng.random() - 0.5) * 0.3
            sh = 0.86 + rng.random() * 0.08
            for k in range(v0, v1):
                p = pos[k]
                dx, dy = (p.x - cx) * sh, (p.y - cy) * sh
                out[k] = Vector((cx + dx, cy + dy, h + (p.z - zb) * 0.55 + tx * dx + ty * dy))
        else:
            zs = [pos[k].z for k in range(v0, v1)]
            if min(zs) > 0.3:
                hc = top - 0.1 + rng.random() * 0.06            # crushed flat under the cap stones
                for k in range(v0, v1): out[k] = Vector((pos[k].x, pos[k].y, min(pos[k].z, hc) * 0 + hc - 0.02 * (pos[k].z - min(zs))))
            else:
                hc = top - 0.04 + rng.random() * 0.08
                for k in range(v0, v1):
                    if pos[k].z > hc: out[k] = Vector((pos[k].x, pos[k].y, hc - rng.random() * 0.03))
    for k in range(len(pos)):
        if k not in done and pos[k].z > top - 0.12:
            r = random.Random(hash((round(pos[k].x, 2), round(pos[k].y, 2), seed))).random()
            out[k] = Vector((pos[k].x, pos[k].y, min(pos[k].z, top - 0.14 + 0.16 * r)))
    return out

def wall_file(name, builder, pal, OUT, variants=3, **kw):
    Ms = [builder(seed, pal, **kw) for seed in range(variants)]
    n = len(Ms[0].v)
    assert all(len(m.v) == n for m in Ms)
    frames_pos = [[p.copy() for p in m.v] for m in Ms]
    frames_pos.append(stub_positions(Ms[0], frames_pos[0]))
    def deform(fi, ci, pos):
        for k in range(n): pos[k] = frames_pos[fi][k]
    # the occlusion bake darkens a vertex next to a taller neighbour, smearing big flat tops: keep a little of it
    return finish_s(name, Ms[0], [[{}] * (variants + 1)], OUT, grounded=False, deform=deform, ao_samples=48, ao_scale=0.35)

