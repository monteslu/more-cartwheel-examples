SPACING = 4.0
def props_file(name, builders, OUT, grounded=True, extra=None):
    """several props in one file, one a frame: each is built at its own spot along x (so the occlusion bake
    sees it alone) on its own bone, and each frame moves the shown one to the origin and folds the rest to a
    point there. builders: [fn(M, bone)] each building round the origin; extra(M) may add shared parts."""
    M = Model()
    M.bone("root", None, (0, 0, 0), (0, 0, 1))
    for k, fn in enumerate(builders):
        off = Vector((SPACING * (k + 1), 0, 0))
        bn = "p%d" % k
        M.bone(bn, "root", tuple(off), tuple(off + Vector((0, 0, 0.2))))
        v0 = len(M.v)
        fn(M, bn)
        for i in range(v0, len(M.v)): M.v[i] = M.v[i] + off
    if extra: extra(M)
    tiny = 1e-4
    frames = []
    for k in range(len(builders)):
        p = {}
        for j in range(len(builders)):
            dx = -SPACING * (j + 1)
            p["p%d" % j] = (0, 0, 0, dx, 0, 0) if j == k else (0, 0, 0, dx, 0, 0, tiny, tiny, tiny)
        frames.append(p)
    return finish_s(name, M, [frames], OUT, grounded=grounded)

