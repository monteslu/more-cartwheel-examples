def skull(M, bone, c, s, col, yaw=0.0, eye=(0.05, 0.04, 0.035)):
    c = Vector(c)
    f = Vector((-math.sin(yaw), -math.cos(yaw), 0))      # facing
    M.ell(bone, tuple(c), (0.1 * s, 0.12 * s, 0.1 * s), col, rot=(0, 0, yaw), seg=(7, 5))
    M.ell(bone, tuple(c + f * 0.07 * s + Vector((0, 0, -0.06 * s))), (0.065 * s, 0.05 * s, 0.045 * s), col, rot=(0, 0, yaw), seg=(5, 3))
    r = Vector((math.cos(yaw), -math.sin(yaw), 0))
    for sd in (-1, 1):
        M.ell(bone, tuple(c + f * 0.095 * s + r * sd * 0.042 * s + Vector((0, 0, 0.005 * s))), (0.032 * s, 0.022 * s, 0.03 * s), (0.05, 0.04, 0.04), seg=(4, 2))

def long_bone(M, bone, a, b, r, col):
    a = Vector(a); b = Vector(b)
    M.limb(bone, a, b, r, r * 0.8, col, seg=5)
    d = (b - a).normalized(); side = d.cross(Vector((0, 0, 1)))
    if side.length < 1e-3: side = Vector((1, 0, 0))
    side.normalize()
    for p in (a, b):
        M.ell(bone, tuple(p + side * r * 0.7), (r * 1.4, r * 1.4, r * 1.3), col, seg=(4, 2))
        M.ell(bone, tuple(p - side * r * 0.7), (r * 1.4, r * 1.4, r * 1.3), col, seg=(4, 2))

def crypt_door(OUT):
    M = root()
    gate(M, CRYPT)
    for x in (-0.6, 0.6):   # skulls on the top rail
        skull(M, "root", (x, -0.03, 2.53), 0.55, CRYPT["bone"])
    return door_file("kit_crypt_door", M, OUT)

def crypt_spawner(OUT):
    """a stone sarcophagus in a heap of bones, its lid cracked, a glow inside; three states of damage (strength
    3, 2, 1) by its pieces moving: the lid shut but cracked, the lid slid off and a side split, the box broken open"""
    M = Model()
    M.bone("root", None, (0, 0, 0), (0, 0, 1))
    pal = CRYPT
    st, st2, bone = (0.62, 0.59, 0.53), (0.47, 0.45, 0.41), pal["bone"]
    rng = random.Random(4)
    def piece(name, c):
        M.bone(name, "root", c, (c[0], c[1], c[2] + 0.2))
    # the glow inside (group 1, white: the game tints it the monster's colour), and a pool of it on the floor
    cuboid(M, "root", (-0.33, -0.6, 0.05), (0.33, 0.6, 0.56), WHITE, group=1, faces="Z", noise_amt=0)
    lathe(M, "root", [(0.0, 0.004), (0.95, 0.004), (0.0, 0.008)], (1.0, 1.0, 1.0), group=1, seg=12, sx=0.85, sy=1.0, noise_amt=0, cap_bot=False)
