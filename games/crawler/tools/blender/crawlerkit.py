def breakable_file(name, pal, OUT, glow=(1.0, 0.85, 0.65), seed=11, courses=(0.0, 0.62, 1.22, 1.8, CAPZ), stones=2):
    """frame 0 a weak block: chunky stones, some missing, a crack across it, a glow inside; frame 1 the rubble"""
    rng = random.Random(seed)
    M = Model()
    M.bone("root", None, (0, 0, 0), (0, 0, 1))
    parts = []
    e = 1 - D
    M.bone("glow", "root", (0, 0, 0), (0, 0, 0.2))
    cuboid(M, "glow", (-0.5, -0.5, 0.0), (0.5, 0.5, CAPZ - 0.2), glow, group=1, faces="xXyYZ", noise_amt=0.0)   # the glow at the heart
    cuboid(M, "root", (-0.62, -0.62, 0), (0.62, 0.62, 0.08), pal["mortar"], faces="xXyYZ", noise_amt=0.2)
    missing = {(0, 2, 0), (0, 1, 1), (3, 2, 1), (2, 3, 0), (1, 1, 0)}
    k_st = 0
    for si, (n, u) in enumerate(SIDES):
        n = Vector(n); u = Vector(u)
        for ci in range(len(courses) - 1):
            z0, z1 = courses[ci], courses[ci + 1]
            for k in range(stones):
                a = -1 + 2 * k / stones; b = a + 2 / stones
                if ci % 2: a, b = a + 0.25, b + 0.25
                a = max(-1, a); b = min(1, b)
                if (si, ci, k) in missing: continue
                cz = (z0 + z1) / 2
                # a crack running up the block diagonally: stones near it shoved out of line and turned
                crack = math.exp(-((a + b) / 2 - (cz - 1.2) * 0.6) ** 2 * 6)
                c = n * (e - 0.12) + u * ((a + b) / 2) + Vector((0, 0, cz))
                bn = "s%d" % k_st; k_st += 1
                M.bone(bn, "root", tuple(c), tuple(c + Vector((0, 0, 0.2))))
                col = pick(rng, pal["stone"])
                if ci == 0 and pal.get("damp"): col = mix(col, pal["damp"], 0.5)
                tilt = (rng.random() - 0.5) * 0.08 * (1 + 2 * crack)
                sh = 0.9 - 0.08 * crack
                rot = (0, 0, tilt) if abs(n.x) > 0.5 else (0, tilt, 0)
                ext = (abs(u.x) * (b - a) * sh + abs(n.x) * 0.24, abs(u.y) * (b - a) * sh + abs(n.y) * 0.24, (z1 - z0) * (0.93 - 0.06 * crack))
                M.box(bn, tuple(c - n * 0.01 * crack), ext, col, rot=rot, bevel=0.03, noise_amt=0.2)
                parts.append((bn, c))
    for i in range(2):
        for k in range(2):
            c = Vector((-0.5 + i, -0.5 + k, CAPZ + 0.11))
            bn = "s%d" % k_st; k_st += 1
            M.bone(bn, "root", tuple(c), tuple(c + Vector((0, 0, 0.2))))
            M.box(bn, tuple(c - Vector((0, 0, 0.012))), (0.92, 0.92, 0.2), pick(rng, pal["cap"]), rot=((rng.random() - 0.5) * 0.05, (rng.random() - 0.5) * 0.05, 0), bevel=0.04, noise_amt=0.2)
            parts.append((bn, c))
    # the rubble: every piece shrunk to a broken chunk and dropped into a low heap
    heap = {"root": (0, 0, 0)}
    hr = random.Random(5)
    rub = {}
    for (bn, c) in parts:
        a = hr.random() * TAU; r = 0.85 * math.sqrt(hr.random())
        x, y = r * math.cos(a), r * math.sin(a)
        z = 0.1 + 0.2 * (1 - r / 0.9) * (0.5 + 0.5 * hr.random())
        s = 0.45 + 0.15 * hr.random()
        # pose location is in the bone's frame: x, z, -y of the world for an upright bone
        dx, dy, dz = x - c.x, y - c.y, z - c.z
        rub[bn] = ((hr.random() - 0.5) * 1.2, hr.random() * TAU, (hr.random() - 0.5) * 1.2, dx, dz, -dy, s, s, s * 0.8)
    rub["root"] = (0, 0, 0)
    rub["glow"] = (0, 0, 0, 0, 0, 0, 1.2, 0.03, 1.2)      # the glow sinks to embers under the heap
    return M, rub

# ───────────────────────── doors ──────────────────────────────────────

def sink_frames(Mv, nframes=6, height=H + 0.05, floor=0.004):
    """the door's vertices sinking into the floor: frame f moved down f/(n-1) of its height, clipped at the floor"""
    out = []
    for f in range(nframes):
        t = f / (nframes - 1)
        dz = height * (t ** 0.8)
        out.append([Vector((p.x, p.y, max(floor * (1 - t) + 0.001, p.z - dz) if t < 1 else min(p.z, 0.004))) for p in Mv])
    return out

def door_file(name, M, OUT, nframes=6):
    fr = sink_frames([p.copy() for p in M.v], nframes)
    n = len(M.v)
    def deform(fi, ci, pos):
        for k in range(n): pos[k] = fr[fi][k]
    return finish_s(name, M, [[{}] * nframes], OUT, grounded=False, deform=deform)

def lock(M, pal, z=1.15, depth=0.2):
    """a heavy lock plate through the door, a keyhole sigil glowing on both faces (group 1, white)"""
    M.box("root", (0, 0, z), (0.5, depth, 0.55), pal["lock"], bevel=0.03, noise_amt=0.15)
    for s in (-1, 1):
        y = s * (depth / 2 + 0.005)
        rot = (math.pi / 2, 0, 0)
        lathe(M, "root", [(0.13, -0.006), (0.17, -0.006), (0.17, 0.006), (0.13, 0.006), (0.13, -0.006)], WHITE, group=1, seg=14, c=(0, y, z + 0.05), rot=rot, noise_amt=0)
        lathe(M, "root", [(0.0, -0.006), (0.045, -0.006), (0.045, 0.006), (0.0, 0.006)], WHITE, group=1, seg=8, c=(0, y, z + 0.08), rot=rot, noise_amt=0)
        prism(M, "root", [(-0.025, 0.0), (0.025, 0.0), (0.045, -0.12), (-0.045, -0.12)], -0.006, 0.006, WHITE, group=1, c=(0, y, z + 0.06), rot=rot, noise_amt=0)
        for kk in range(4):
            a = TAU * kk / 4 + 0.785
            M.ell("root", (0.19 * math.cos(a), y * 1.05, z + 0.2 * math.sin(a)), (0.03, 0.02, 0.03), pal["iron"], seg=(6, 3))

def gate(M, pal, bars=9, sigil=None, finial="spike", bar=0.07, wobble=0.0, rails=(0.12, 1.05, 2.2), seed=1):
    """a portcullis filling the tile's gap (x -1..1, thin in y): bars, rails, a lock plate with a glowing sigil"""
    iron, diron = pal["iron"], pal["diron"]
    rng = random.Random(seed)
    top = 2.45
    for k in range(bars):
        x = (-0.92 + 1.84 * k / (bars - 1)) * (1 - wobble * 0.8)
        if wobble:
            # a crooked bar: three segments leaning a little each way
            pts = [(x + (rng.random() - 0.5) * wobble, 0, z) for z in (0.0, 0.8, 1.6, top)]
            for j in range(3):
                M.limb("root", pts[j], pts[j + 1], bar * 0.6, bar * 0.55, iron if k % 2 else diron, seg=5, noise_amt=0.3)
        else:
            M.box("root", (x, 0, top / 2), (bar, bar, top), iron if k % 2 else diron, bevel=0.012, noise_amt=0.25)
        if finial == "spike":
            M.spike("root", (x, 0, top - 0.02), (x, 0, top + 0.13), bar * 0.7, iron, seg=4)
        elif finial == "orb":
            g = pal.get("gold", iron)
            g = g[0] if isinstance(g[0], tuple) else g
            M.ell("root", (x, 0, top + 0.07), (0.05, 0.05, 0.06), g, seg=(6, 4))
            M.spike("root", (x, 0, top + 0.1), (x, 0, top + 0.24), 0.025, g, seg=4)
    for z in rails:
        M.box("root", (0, 0, z), (1.98, 0.11, 0.1), diron, bevel=0.015, noise_amt=0.2)
    M.box("root", (0, 0, top + 0.02), (1.98, 0.13, 0.06), diron, bevel=0.012)
    lock(M, pal)
    if sigil: sigil(M)

