    # each flame cluster scaled about its own base
    groups = []
    for i in sorted(fl):
        for g in groups:
            if (Vector((M.v[i].x, M.v[i].y, 0)) - g[0]).length < 0.12:
                g[1].append(i); break
        else:
            groups.append((Vector((M.v[i].x, M.v[i].y, 0)), [i]))
