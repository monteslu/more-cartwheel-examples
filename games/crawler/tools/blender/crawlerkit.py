# Crawler's tile kits and items, headless:
#   flatpak run --filesystem=home org.blender.Blender --background --factory-startup --python \
#     <abs>/tools/blender/crawlerkit.py -- <abs out dir> [name ...]
# names: see KIT at the end (default all).
#
# Every model is a .cwchar (format in hordechars.py): group 0 lit with vertex colours (colours above 1.5 are
# HDR emissive), group 1 an unlit glow the game multiplies by a per-instance colour. Game axes: metres, y up;
# here Blender's z is up and the game's +Z is Blender's -Y. One topology per file, so a file's frames are the
# same vertices moved: a wall's variants are the same stones placed differently, its stub the same stones cut
# down; a door sinks; a spawner's damage moves its pieces; frames that are different props (decor, food,
# charms) carry every prop and fold away the ones not shown to a point on the floor.
# Wall tiles: footprint x, z in [-1, 1], top at 2.6; nothing pokes outside the footprint, every side face is the
# same, so blocks abut and rotate freely. Every shape here is generated by this script (no outside art).
