def rock_wall(seed, pal):
    """a lump of cave rock filling the footprint: a subdivided box pushed in by noise (never out), moss on its
    top, glowing fungus on its faces"""
    import bmesh as _bm
    M = root()
    bm = _bm.new()
    _bm.ops.create_cube(bm, size=1.0)
    _bm.ops.subdivide_edges(bm, edges=list(bm.edges), cuts=4, use_grid_fill=True)
    bot = [f for f in bm.faces if f.normal.z < -0.9]
    _bm.ops.delete(bm, geom=bot, context='FACES')
    off = Vector((seed * 7.3, seed * 3.1, 0))
    for v in bm.verts:
        p = Vector((v.co.x * 2, v.co.y * 2, (v.co.z + 0.5) * H))
        # inward push along the box's own sides: little low down (so neighbours meet), more toward a rounded top
        q = p * 1.1 + off
        nz = noise.noise(q) * 0.5 + 0.5
        nz2 = noise.noise(q * 2.9 + Vector((5, 5, 5))) * 0.5 + 0.5
        up = smooth01((p.z - 1.5) / 1.1)
        push = 0.01 + 0.07 * nz + 0.05 * nz2 + 0.3 * up * (0.5 + nz)
        if p.z > 0.01:
            if abs(p.x) > 0.999: p.x -= math.copysign(push, p.x)
            if abs(p.y) > 0.999: p.y -= math.copysign(push, p.y)
        if p.z > H - 0.01:
            p.z -= 0.05 + 0.3 * nz2
            p.x *= 0.8 + 0.1 * nz; p.y *= 0.8 + 0.1 * nz
        elif p.z > 0.01:
            p.z *= 1 - 0.06 * nz2
        v.co = p
    bm.normal_update()
    bm.verts.index_update()
    uv = bm.loops.layers.uv.new()
    v0 = len(M.v)
    M._add(bm, Matrix.Identity(4), {"root": 1.0}, pal["stone"][0], 0, False, (1, 1), 0.25)
    bm.free()
    crng = random.Random(1000 + seed)
    for k in range(v0, len(M.v)):
        p = M.v[k]
        base = pal["stone"][k % len(pal["stone"])]
        patch = smooth01((noise.noise(p * 1.7 + Vector((3, 1, 0))) + 0.1) * 3)
        t = smooth01((p.z - 1.9) / 0.4) * patch
        c = mix(base, pal["moss"], t * 0.9)
        if p.z < 0.4: c = mix(c, pal["damp"], 0.5 * (1 - p.z / 0.4))
        kk = 0.85 + 0.3 * (noise.noise(p * 2.2) * 0.5 + 0.5)
        M.col[k] = (c[0] * kk, c[1] * kk, c[2] * kk)
    # fungus: three clusters of glowing caps on the faces, low and high
    rng = random.Random(77)
    srng = random.Random(seed)
    for k in range(3):
        si = (k + seed) % 4
        n, u = SIDES[si]; n = Vector(n); u = Vector(u)
        a = (srng.random() - 0.5) * 1.2; z = 0.3 + srng.random() * 1.6
        for j in range(3):
            c = n * 0.86 + u * (a + (j - 1) * 0.09) + Vector((0, 0, z + 0.05 * (j % 2)))
            M.ell("root", tuple(c), (0.07 - 0.015 * j, 0.07 - 0.015 * j, 0.025), pal["fungus"], group=1, rot=(0, 0, 0), seg=(5, 2), noise_amt=0)
    M.stub_mode = "scale"
    return M

def smooth01(t):
    t = max(0.0, min(1.0, t))
    return t * t * (3 - 2 * t)

