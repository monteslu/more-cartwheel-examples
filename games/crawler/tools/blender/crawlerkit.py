def block_wall(seed, pal, courses, cap="slabs", extra=None, cap_h=0.22, cap_ch=0.07, jag=0.025, dent=0.03, peak=0.0):
    """A block of courses: courses is [(z0, z1, stones, kind, colour key, gap)], kind "pillow" (a chamfered
    stone), "brick" (its face and top edge only: four triangles), "slab" (a pillow without its bottom edge),
    gap the width of an opening in the middle of each face (0 for none). The core, corner columns, quoined
    corners and the cap are ashlar_wall's. extra(M, rng, crng) adds a kit's features (same topology every seed)."""
    rng = random.Random(seed)
    crng = random.Random(1000)
    M = root()
    e = 1 - D
    cuboid(M, "root", (-e, -e, 0), (e, e, CAPZ + 0.01), pal["mortar"], faces="xXyYZ", noise_amt=0.2)
    for sx in (-1, 1):
        for sy in (-1, 1):
            x0, x1 = sorted((sx * e, sx * 0.995)); y0, y1 = sorted((sy * e, sy * 0.995))
            cuboid(M, "root", (x0, y0, 0), (x1, y1, CAPZ), pal["mortar"], faces=("X" if sx > 0 else "x") + ("Y" if sy > 0 else "y"), noise_amt=0.2)
    for si, (n, u) in enumerate(SIDES):
        n = Vector(n); u = Vector(u)
        for ci, (z0, z1, stones, kind, ck, gap) in enumerate(courses):
            full = (si >= 2) == (ci % 2 == 0)
            lo, hi = (-1.0, 1.0) if full else (-e, e)
            spans = [(lo, -gap / 2), (gap / 2, hi)] if gap else [(lo, hi)]
            per = max(1, stones // len(spans))
            for (a0, a1) in spans:
                cuts = [a0]
                for k in range(1, per):
                    t = a0 + (a1 - a0) * (k / per + (0.5 / per if ci % 2 else 0) * 0.5 + (rng.random() - 0.5) * 0.25 / per)
                    cuts.append(max(a0 + 0.12, min(a1 - 0.12, t)))
                cuts.append(a1)
                cuts.sort()
                for k in range(per):
                    a, b = cuts[k], cuts[k + 1]
                    c = n * e + u * ((a + b) / 2) + Vector((0, 0, (z0 + z1) / 2))
                    col = pick(crng, pal[ck])
                    if ci == 0 and pal.get("damp"): col = mix(col, pal["damp"], 0.45 + 0.3 * crng.random())
                    if crng.random() < pal.get("stain_p", 0.0): col = mix(col, pal["stain"], 0.4 + 0.3 * crng.random())
                    j = [(rng.random() - 0.5) * jag for _ in range(4)]
                    tt = rng.random() * peak if peak else 0.0
                    d = min(D - rng.random() * 0.02, D - max(j) - 0.001) - tt - (0.03 if ck == "plate" else 0.0)
                    ch = min(0.03 + rng.random() * 0.025, 0.4 * (z1 - z0), 0.4 * (b - a))
                    keep = {"brick": "t", "slab": "rtl", "pillow": "brtl"}[kind]
                    v0 = len(M.v)
                    pillow(M, "root", c, u, (0, 0, 1), n, (b - a) / 2, (z1 - z0) / 2, d, ch, col, jit=j, noise_amt=0.15, keep=keep, tri_top=tt)
                    mark(M, v0, "side")
    if cap == "plate":
        # one iron plate over the whole top, rivets round its edge, a glowing vent slot across it
        hh = cap_h - 0.02
        v0 = len(M.v)
        pillow(M, "root", Vector((0, 0, CAPZ)), (1, 0, 0), (0, 1, 0), (0, 0, 1), 1.0, 1.0, hh, cap_ch, pick(crng, pal["cap"]), noise_amt=0.2)
        top = CAPZ + hh
        for k in range(12):
            t = -0.84 + 1.68 * (k % 3) / 2
            x, y = [(t, -0.86), (t, 0.86), (-0.86, t), (0.86, t)][k // 3]
            pillow(M, "root", Vector((x, y, top)), (1, 0, 0), (0, 1, 0), (0, 0, 1), 0.035, 0.035, 0.0, 0.012, (0.45, 0.42, 0.4), keep="", tri_top=0.02)
        L = 0.45 + 0.35 * rng.random(); o = (rng.random() - 0.5) * 0.6
        a, b = (-L, o - 0.04), (L, o + 0.04)
        if seed % 2: a, b = (o - 0.04, -L), (o + 0.04, L)
        mesh(M, "root", [(a[0], a[1], top + 0.004), (b[0], a[1], top + 0.004), (b[0], b[1], top + 0.004), (a[0], b[1], top + 0.004)], [(0, 1, 2, 3)], pal["hot"], group=1, noise_amt=0)
        mark(M, v0, "cap")
    else:
        inner = 0.84 if cap == "rimmed" else 1.0
        for (x0, y0, x1, y1) in cap_layout(seed, rng):
            x0, y0, x1, y1 = x0 * inner, y0 * inner, x1 * inner, y1 * inner
            c = Vector(((x0 + x1) / 2, (y0 + y1) / 2, CAPZ))
            col = pick(crng, pal["cap"])
            j = [(rng.random() - 0.5) * jag for _ in range(4)]
            tt = (0.05 + rng.random() * 0.12) if cap == "jag" else (rng.random() - 0.6) * dent
            hh = cap_h - 0.012 - max(j) - max(0.0, tt) - (0.03 if cap == "rimmed" else 0.0)
            v0 = len(M.v)
            pillow(M, "root", c, (1, 0, 0), (0, 1, 0), (0, 0, 1), (x1 - x0) / 2, (y1 - y0) / 2, hh, cap_ch, col, jit=j, noise_amt=0.18, tri_top=tt)
            mark(M, v0, "cap")
        if cap == "rimmed":
            # a gilded rim round the top's edge
            for (x0, y0, x1, y1) in ((-1, -1, 1, -inner), (-1, inner, 1, 1), (-1, -inner, -inner, inner), (inner, -inner, 1, inner)):
                v0 = len(M.v)
                pillow(M, "root", Vector(((x0 + x1) / 2, (y0 + y1) / 2, CAPZ)), (1, 0, 0), (0, 1, 0), (0, 0, 1), (x1 - x0) / 2, (y1 - y0) / 2,
                       cap_h - 0.012, 0.035, pick(crng, pal["gold"]), noise_amt=0.1)
                mark(M, v0, "cap")
    if extra: extra(M, rng, crng)
    return M

def face_quad(M, si, a, b, z0, z1, depth, color, group=1, bone="root"):
    """a flat quad on side si's face plane at depth in from the footprint (for glass, seams, cracks)"""
    n, u = SIDES[si]
    n = Vector(n); u = Vector(u)
    o = n * (1 - depth)
    V = [o + u * a + Vector((0, 0, z0)), o + u * b + Vector((0, 0, z0)), o + u * b + Vector((0, 0, z1)), o + u * a + Vector((0, 0, z1))]
    mesh(M, bone, [tuple(p) for p in V], [(0, 1, 2, 3)], color, group=group, noise_amt=0)

def face_strip(M, si, pts, wdt, depth, color, group=1):
    """a zigzag strip on side si's face through (u, z) points"""
    n, u = SIDES[si]
    n = Vector(n); u = Vector(u)
    o = n * (1 - depth)
    for k in range(len(pts) - 1):
        (a0, z0), (a1, z1) = pts[k], pts[k + 1]
        d = Vector((a1 - a0, z1 - z0)); L = d.length; px, pz = -d.y / L * wdt, d.x / L * wdt
        V = [o + u * (a0 - px) + Vector((0, 0, z0 - pz)), o + u * (a1 - px) + Vector((0, 0, z1 - pz)),
             o + u * (a1 + px) + Vector((0, 0, z1 + pz)), o + u * (a0 + px) + Vector((0, 0, z0 + pz))]
        if (V[1] - V[0]).cross(V[2] - V[1]).dot(n) < 0: V = V[::-1]      # always facing out of the face
        mesh(M, "root", [tuple(p) for p in V], [(0, 1, 2, 3)], color, group=group, noise_amt=0)

