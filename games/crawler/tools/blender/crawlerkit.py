def kit_breakable_over(kit, pal, top, glow, OUT, seed=7):
    """the kit's own wall block, cracked: its top pieces pushed apart and tipped so the glowing core shows in
    every joint, glowing cracks across the top (group 1); frame 1 the same pieces fallen into a low heap"""
    M = top_wall(seed, pal, top, core_glow=glow)
    rng = random.Random(seed * 3 + 1)
    # cracks: zigzags of glow across the top, drawn just over it
    v_crack = len(M.v)
    for pts in (((-0.95, -0.55), (-0.5, -0.25), (-0.15, -0.45), (0.25, -0.1), (0.55, -0.3), (0.95, 0.05)),
                ((-0.2, 0.95), (-0.05, 0.55), (0.25, 0.4), (0.15, 0.05)), ((-0.9, 0.35), (-0.55, 0.45), (-0.35, 0.8))):
        for k in range(len(pts) - 1):
            (x0, y0), (x1, y1) = pts[k], pts[k + 1]
            dx, dy = x1 - x0, y1 - y0; L = math.hypot(dx, dy); w = 0.045 if k % 2 == 0 else 0.03
            px, py = -dy / L * w, dx / L * w
            z = H + 0.006
            mesh(M, "root", [(x0 - px, y0 - py, z), (x1 - px, y1 - py, z), (x1 + px, y1 + py, z), (x0 + px, y0 + py, z)], [(0, 1, 2, 3)], glow, group=1, noise_amt=0)
    v_end = len(M.v)
    rest = [p.copy() for p in M.v]
    pieces = getattr(M, "pieces", [])
    in_piece = set()
    for (a, b, kind) in pieces: in_piece.update(range(a, b))
    # frame 0: every piece nudged out from the centre and tipped a little
    f0 = [p.copy() for p in rest]
    for (a, b, kind) in pieces:
        ps = rest[a:b]
        c = sum(ps, Vector()) / len(ps)
        out = Vector((c.x, c.y, 0)); out = out.normalized() * (0.04 + 0.03 * rng.random()) if out.length > 0.05 else Vector((0.03, 0.02, 0))
        tx, ty = (rng.random() - 0.5) * 0.06, (rng.random() - 0.5) * 0.06
        for i in range(a, b):
            p = rest[i]
            q = Vector((p.x + out.x, p.y + out.y, p.z + tx * (p.x - c.x) + ty * (p.y - c.y) - (0.03 if kind == "cap" else 0.0)))
            q.x = max(-1.0, min(1.0, q.x)); q.y = max(-1.0, min(1.0, q.y))
            f0[i] = q
    for i in range(v_crack, v_end): f0[i] = Vector((rest[i].x, rest[i].y, H + 0.004))
    # frame 1: the rubble
    f1 = [Vector((p.x * 0.6, p.y * 0.6, 0.004)) for p in rest]
    hr = random.Random(5)
    for (a, b, kind) in pieces:
        ps = rest[a:b]
        c = sum(ps, Vector()) / len(ps)
        ang = hr.random() * TAU; r = 0.85 * math.sqrt(hr.random())
        tgt = Vector((r * math.cos(ang), r * math.sin(ang), 0.08 + 0.2 * (1 - r / 0.9) * (0.5 + 0.5 * hr.random())))
        R = (Matrix.Rotation(hr.random() * TAU, 3, 'Z') @ Matrix.Rotation((hr.random() - 0.5) * 1.0, 3, 'X'))
        s_ = 0.42 + 0.12 * hr.random()
        for i in range(a, b):
            q = R @ ((rest[i] - c) * s_) + tgt
            q.z = max(0.0, q.z)
            f1[i] = q
    for i in range(v_crack, v_end): f1[i] = Vector((rest[i].x * 0.5, rest[i].y * 0.5, 0.01))
    n = len(M.v)
    fr = [f0, f1]
    def deform(fi, ci, pos):
        for k in range(n): pos[k] = fr[fi][k]
    return finish_s("kit_%s_breakable" % kit, M, [[{}, {}]], OUT, grounded=True, deform=deform, ao_scale=0.4)

