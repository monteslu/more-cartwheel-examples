// The descent's level layouts and lighting scenes (LEVELS.md): writes assets/levels/<id>.cwlevel and
// assets/scenes/<id>.cwscene for each level from the design below, deterministic (seeded). Obstacle half
// extents come from the props' own .cwchar bounds, so build the models first (tools/blender/levelprops.py).
//   node tools/gen-levels.mjs [level ...]
// Axes as the game's: x east, z south, y up; the camera looks from the south. A prop's front (its -Y in
// Blender) faces +z at yaw 0.
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readCwchar } from './cwchar-info.mjs';

const GAME = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const A = (p) => resolve(GAME, 'assets', p);
const HALF = 38, W = HALF + 1;
const PI = Math.PI;

function rng(seed) { // mulberry32
  let a = seed >>> 0;
  return () => { a = (a + 0x6d2b79f5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
const f = (x) => (Math.abs(x) < 5e-5 ? 0 : +x.toFixed(4)).toString();

class Level {
  constructor(id, name) {
    Object.assign(this, { id, name, props: [], at: [], lights: [], hazards: [], spawns: [], pickups: [], shrines: [], obstacles: [], waves: [] });
    this.bounds = {};
  }
  prop(name, file, tx, rep, rough, metal, solid) {
    const path = A(file);
    if (!existsSync(path)) throw new Error(`${file} missing: build the models first (tools/blender/levelprops.py)`);
    const b = readCwchar(path);
    this.bounds[name] = b;
    this.props.push({ name, file, tx, rep, rough, metal, solid });
    return name;
  }
  put(name, x, z, yaw = 0, y = 0) {
    const p = this.props.find((q) => q.name === name);
    const b = this.bounds[name];
    let hx = 0, hz = 0;
    if (p.solid) { // the rotated footprint's half extents about the placement (the sim's box)
      const c = Math.cos(yaw), s = Math.sin(yaw);
      for (const [lx, lz] of [[b.lo[0], b.lo[2]], [b.hi[0], b.lo[2]], [b.lo[0], b.hi[2]], [b.hi[0], b.hi[2]]]) {
        hx = Math.max(hx, Math.abs(lx * c + lz * s));
        hz = Math.max(hz, Math.abs(-lx * s + lz * c));
      }
    }
    this.at.push({ name, x, y, z, yaw, hx, hz, solid: p.solid });
  }
  // a wall of a prop 4 m long round the arena's edge (the yard's walls), with gaps
  ring(name, gapAt = () => false, alt = null) {
    for (let side = 0; side < 4; side++) {
      const yaw = [0, PI, PI / 2, -PI / 2][side];
      for (let i = 0; i < 19; i++) {
        const a = -HALF + 2 + 4 * i;
        const [x, z] = side < 2 ? [a, side === 0 ? -W : W] : [side === 2 ? -W : W, a];
        if (gapAt(side, a)) { if (alt) this.put(alt, x, z, yaw); } else this.put(name, x, z, yaw);
      }
    }
  }
  light(type, [x, y, z], [tx, ty, tz], [r, g, b], energy, range, angle = 0.6, penumbra = 0.6, bakeOnly = 1) {
    this.lights.push({ type, x, y, z, tx, ty, tz, r, g, b, energy, range, angle, penumbra, bakeOnly });
  }
  text() {
    const L = [];
    L.push(`# ${this.name}: generated by tools/gen-levels.mjs (the design is LEVELS.md); edit the generator, not this file`);
    L.push(`level ${this.id} ${this.name}`);
    L.push(`waves ${this.waves.length}`);
    L.push(`roster ${this.roster.join(' ')}`);
    this.waves.forEach((w, i) => L.push(`wave ${i + 1} ${w}`));
    L.push(`monster ${this.monster}`);
    L.push(`boss ${this.boss} ${this.bossName}`);
    L.push(`scene scenes/${this.id}.cwscene`);
    L.push(`lightmap lightmaps/${this.id}.cwlm`);
    L.push(`floor ${this.floor.tex} ${f(this.floor.tile)} ${f(this.floor.rough)} ${this.floor.tint.map(f).join(' ')}`);
    for (const p of this.props) L.push(`prop ${p.name} ${p.file} ${p.tx} ${f(p.rep)} ${f(p.rough)} ${f(p.metal)} ${p.solid}`);
    for (const o of this.obstacles) L.push(`obstacle ${o.kind} ${o.file}`);
    L.push(`door ${this.door} 0 0`);
    for (const a of this.at) L.push(`at ${a.name} ${f(a.x)} ${f(a.y)} ${f(a.z)} ${f(a.yaw)}${a.solid ? ` ${f(a.hx)} ${f(a.hz)}` : ''}`);
    for (const s of this.spawns) L.push(`spawn ${s.map(f).join(' ')}`);
    for (const p of this.pickups) L.push(`pickup ${p.map(f).join(' ')}`);
    for (const s of this.shrines) L.push(`shrine ${s.map(f).join(' ')}`);
    for (const h of this.hazards) L.push(`hazard ${h.kind} ${[h.x, h.z, h.hx, h.hz].map(f).join(' ')}`);
    for (const l of this.lights) L.push(`light ${l.type} ${[l.x, l.y, l.z, l.tx, l.ty, l.tz, l.r, l.g, l.b, l.energy, l.range, l.angle, l.penumbra].map(f).join(' ')} ${l.bakeOnly}`);
    return L.join('\n') + '\n';
  }
}

// the lighting scene: the key (Sun) and rim lights, the environment and the post stack, with the yard's
// node names (arena.cwscene)
function scene(id, s) {
  return `[scene format=1]

; ${s.title}: generated by tools/gen-levels.mjs (the design is LEVELS.md)
[node name="${id}" type="Node3D"]

; the key: ${s.keyNote}
[node name="Sun" parent="." type="DirectionalLight3D"]
position = vec3(${s.sun.dir.map(f).join(', ')})
color = color(${s.sun.color.map(f).join(', ')}, 1)
energy = ${f(s.sun.energy)}
shadow = false
fog_energy = ${f(s.sun.fog ?? 1)}
bake_direct = true

; the rim: edging every character against the dark
[node name="Rim" parent="." type="DirectionalLight3D"]
position = vec3(${s.rim.dir.map(f).join(', ')})
color = color(${s.rim.color.map(f).join(', ')}, 1)
energy = ${f(s.rim.energy)}
fog_energy = 0
bake_direct = true

[node name="Env" parent="." type="WorldEnvironment"]
background = color(${s.bg.map(f).join(', ')}, 1)
ambient_color = color(${s.ambient.map(f).join(', ')}, 1)
ambient_energy = ${f(s.ambientEnergy)}
sky_color = color(${s.sky.map(f).join(', ')}, 1)
ground_color = color(${s.ground.map(f).join(', ')}, 1)
hemi_energy = ${f(s.hemi)}
fog_mode = EXP2
fog_color = color(${s.fog.map(f).join(', ')}, 1)
fog_density = ${f(s.fogDensity)}

[node name="Post" parent="." type="PostProcess"]
depth_prepass = false
fuse_distortion = true
tonemap = AGX
exposure = ${f(s.exposure)}
bloom = true
bloom_intensity = ${f(s.bloom)}
bloom_threshold = 1.0
bloom_knee = 0.6
ssao = false
ssr = false
aa = FXAA
grade = true
grade_intensity = 0.9
lut = "grade/${id}.cube"
vignette = true
vignette_intensity = ${f(s.vignette)}
vignette_smoothness = 0.6
grain = true
grain_intensity = 0.035
`;
}

// ── level 2: the Drowned Sluice ─────────────────────────────────────
function sluice() {
  const L = new Level('sluice', 'The Drowned Sluice');
  const r = rng(202);
  L.roster = ['runner', 'brute', 'bloater', 'skitter'];
  L.waves = ['runner:70 skitter:30', 'runner:50 skitter:50', 'runner:40 brute:20 skitter:40', 'runner:30 bloater:20 skitter:50', 'boss skitter:60 runner:40'];
  L.monster = 'models/sluice_skitter.cwchar';
  L.boss = 'models/sluice_boss.cwchar'; L.bossName = 'Vhessa, Mother of the Drains';
  L.door = 'models/sluice_door.cwchar';
  L.floor = { tex: 'textures/sluice_floor.png', tile: 8, rough: 0.55, tint: [0.92, 1.0, 0.98] };
  const wall = L.prop('wall', 'models/sluice_wall.cwchar', 'pillar', 1, 0.85, 0, 0);
  const gate = L.prop('gate', 'models/sluice_gate.cwchar', 'armor', 1, 0.6, 0.4, 0);
  const pier = L.prop('pier', 'models/sluice_pier.cwchar', 'pillar', 1, 0.85, 0, 1);
  const curb = L.prop('curb', 'models/sluice_curb.cwchar', 'pillar', 1, 0.8, 0, 0);
  const lamp = L.prop('lamp', 'models/sluice_lamp.cwchar', 'armor', 1, 0.6, 0.5, 0);
  const crate = L.prop('crate', 'models/sluice_crate.cwchar', 'hide', 1, 0.85, 0, 3);
  const drum = L.prop('drum', 'models/sluice_drum.cwchar', 'armor', 1, 0.6, 0.6, 4);
  const pipe = L.prop('pipe', 'models/sluice_pipe.cwchar', 'pillar', 1, 0.8, 0, 0);
  L.obstacles = [{ kind: 'crate', file: 'models/sluice_crate.cwchar' }, { kind: 'barrel', file: 'models/sluice_drum.cwchar' }, { kind: 'pillar', file: 'models/sluice_pier.cwchar' }];
  // the vault walls with six culvert mouths: north and south in the middle, east and west at z -12 and 12
  const gapAt = (side, a) => (side < 2 ? Math.abs(a) < 2.5 : Math.abs(Math.abs(a) - 12) < 2.5);
  L.ring(wall, gapAt, gate);
  for (const [x, z, yaw] of [[0, -W - 3.5, 0], [0, W + 3.5, PI], [-W - 3.5, -12, PI / 2], [-W - 3.5, 12, PI / 2], [W + 3.5, -12, -PI / 2], [W + 3.5, 12, -PI / 2]])
    L.put(pipe, x, z, yaw); // the culverts behind the gates
  L.spawns = [[0, -38, 2], [0, 38, 2], [-38, -12, 2], [-38, 12, 2], [38, -12, 2], [38, 12, 2]];
  // the water channel: a square ring 16 to 21 m out, a dry causeway 6 m wide across the middle of each side
  const IN = 16, OUT = 21, CW = 3;
  const half = (OUT - IN) / 2, mid = (OUT + IN) / 2;
  for (const s of [-1, 1]) {
    for (const t of [-1, 1]) {
      const len = OUT - CW;
      L.hazards.push({ kind: 'water', x: t * (CW + len / 2), z: s * mid, hx: len / 2, hz: half }); // north / south runs
      const lz = IN - CW;
      L.hazards.push({ kind: 'water', x: s * mid, z: t * (CW + lz / 2), hx: half, hz: lz / 2 });   // east / west runs
    }
  }
  // curbs along the channel's edges (a 4 m length each, along the run)
  for (const s of [-1, 1]) for (const edge of [IN - 0.2, OUT + 0.2]) {
    for (let a = -OUT + 2; a <= OUT - 2; a += 4) {
      if (Math.abs(a) < CW + 1.5) continue;
      if (Math.abs(a) > (edge < mid ? IN : OUT) + 0.5) continue;
      L.put(curb, a, s * edge, 0);
      L.put(curb, s * edge, a, PI / 2);
    }
  }
  // brick piers: the outer ring (cover near the walls) and four inside the channel
  for (const [x, z] of [[-28, -28], [28, -28], [-28, 28], [28, 28], [-28, -6], [28, -6], [-28, 6], [28, 6], [-9, -10], [9, -10], [-9, 10], [9, 10]]) L.put(pier, x, z, 0);
  // crates and drums: in the outer band and inside the channel, never on the water, the causeways or the hatch
  const wet = (x, z) => L.hazards.some((h) => Math.abs(x - h.x) < h.hx + 1 && Math.abs(z - h.z) < h.hz + 1);
  const busy = (x, z, rad) => L.at.some((a) => a.solid && Math.abs(x - a.x) < a.hx + rad && Math.abs(z - a.z) < a.hz + rad);
  let nc = 0, nd = 0, tries = 0;
  while ((nc < 22 || nd < 12) && tries++ < 5000) {
    const x = (r() - 0.5) * 2 * (HALF - 3), z = (r() - 0.5) * 2 * (HALF - 3);
    if (Math.hypot(x, z) < 7 || wet(x, z) || busy(x, z, 1.6) || (Math.abs(x) < 4 && Math.abs(z) > IN - 1) || (Math.abs(z) < 4 && Math.abs(x) > IN - 1)) continue;
    if (nc < 22) {
      L.put(crate, x, z, r() * PI);
      if (nc % 5 === 0) { const b = L.bounds.crate; L.put(crate, x + 0.05, z - 0.04, r() * PI, b.hi[1]); } // a second crate stacked on it
      nc++;
    } else { L.put(drum, x, z, r() * PI); nd++; }
  }
  // failing sodium lamps along the walls (their pools baked; the glow drawn), and the key through the grating
  const lampAt = [[-26, -W + 0.6, 0], [-8, -W + 0.6, 0], [14, -W + 0.6, 0], [30, -W + 0.6, 0], [-22, W - 0.6, PI], [6, W - 0.6, PI], [26, W - 0.6, PI],
    [-W + 0.6, -26, PI / 2], [-W + 0.6, 2, PI / 2], [-W + 0.6, 26, PI / 2], [W - 0.6, -24, -PI / 2], [W - 0.6, 0, -PI / 2], [W - 0.6, 24, -PI / 2]];
  lampAt.forEach(([x, z, yaw], i) => {
    L.put(lamp, x, z, yaw);
    const fx = Math.sin(yaw), fz = Math.cos(yaw);
    const dead = i % 5 === 3; // one in five has failed: its post stands dark
    if (!dead) L.light('spot', [x + fx * 0.75, 3.3, z + fz * 0.75], [x + fx * 7, 0, z + fz * 7], [1.0, 0.62, 0.28], 520, 26, 0.85, 0.7, 1);
  });
  // cold light pooling under the broken grating (north-east), and a cool bounce over the middle
  L.light('spot', [18, 22, -20], [12, 0, -10], [0.62, 0.8, 0.95], 2600, 46, 0.42, 0.85, 1);
  L.light('omni', [0, 6, 0], [0, 0, 0], [0.45, 0.65, 0.62], 260, 22, 0, 0, 1);
  L.pickups = [[-34, -34], [34, -34], [-34, 34], [34, 34], [0, -18.5], [0, 18.5], [-18.5, 0], [18.5, 0], [-12, -28], [12, 28]];
  L.scene = {
    title: 'The Drowned Sluice', keyNote: 'cold light falling through a broken grating in the north-east, low and hard',
    sun: { dir: [22, 30, -18], color: [0.62, 0.78, 0.92], energy: 1.6, fog: 1.2 },
    rim: { dir: [-24, 8, 20], color: [0.35, 0.75, 0.62], energy: 1.1 },
    bg: [0.01, 0.018, 0.018], ambient: [0.3, 0.42, 0.4], ambientEnergy: 0.22, sky: [0.32, 0.45, 0.45], ground: [0.05, 0.06, 0.05], hemi: 0.3,
    fog: [0.06, 0.09, 0.08], fogDensity: 0.014, exposure: 1.2, bloom: 0.16, vignette: 0.45,
  };
  return L;
}

// ── level 3: the Ossuary ────────────────────────────────────────────
function ossuary() {
  const L = new Level('ossuary', 'The Ossuary');
  const r = rng(303);
  L.roster = ['runner', 'brute', 'bloater', 'skitter', 'bonewalker'];
  L.waves = ['runner:60 bonewalker:40', 'runner:40 brute:30 bonewalker:30', 'skitter:30 bonewalker:70', 'runner:20 bloater:20 skitter:20 bonewalker:40', 'boss bonewalker:50 runner:30 brute:20'];
  L.monster = 'models/ossuary_bonewalker.cwchar';
  L.boss = 'models/ossuary_boss.cwchar'; L.bossName = 'Ossivar, the Hollow Abbot';
  L.door = 'models/ossuary_door.cwchar';
  L.floor = { tex: 'textures/ossuary_floor.png', tile: 9, rough: 0.9, tint: [1.0, 0.97, 0.92] };
  const outer = L.prop('outer', 'models/ossuary_outer.cwchar', 'pillar', 1, 0.9, 0, 0);
  const wall = L.prop('bonewall', 'models/ossuary_wall.cwchar', 'pillar', 1, 0.9, 0, 1);
  const column = L.prop('column', 'models/ossuary_column.cwchar', 'pillar', 1, 0.9, 0, 1);
  const sarc = L.prop('sarcophagus', 'models/ossuary_sarcophagus.cwchar', 'pillar', 1, 0.9, 0, 1);
  const pile = L.prop('bonepile', 'models/ossuary_bonepile.cwchar', 'hide', 1, 0.85, 0, 3);
  const urn = L.prop('urn', 'models/ossuary_urn.cwchar', 'hide', 1, 0.7, 0, 4);
  const brazier = L.prop('brazier', 'models/ossuary_brazier.cwchar', 'armor', 1, 0.6, 0.6, 1);
  const candles = L.prop('candles', 'models/ossuary_candles.cwchar', 'pillar', 1, 0.9, 0, 0);
  L.obstacles = [{ kind: 'crate', file: 'models/ossuary_bonepile.cwchar' }, { kind: 'barrel', file: 'models/ossuary_urn.cwchar' }, { kind: 'pillar', file: 'models/ossuary_column.cwchar' }];
  // the outer vault wall; gaps north and south at x -4 and 4, east and west at z -12 and 12
  const gapAt = (side, a) => (side < 2 ? Math.abs(Math.abs(a) - 4) < 1.5 : Math.abs(Math.abs(a) - 12) < 1.5);
  L.ring(outer, gapAt);
  L.spawns = [[-4, -38, 2], [4, -38, 2], [-4, 38, 2], [4, 38, 2], [-38, -12, 2], [-38, 12, 2], [38, -12, 2], [38, 12, 2]];
  // four crypt chambers in the corners: a skull wall along z = +-16 (x from the edge to +-12, a 4 m doorway at
  // x = +-22) and along x = +-12 (z from the edge to +-16, a doorway at z = +-24). The skull face looks south
  // (toward the camera) on the east-west walls and toward the nave on the north-south ones.
  for (const sx of [-1, 1]) for (const sz of [-1, 1]) {
    for (const a of [34, 30, 26, 18, 14]) L.put(wall, sx * a, sz * 16, 0);
    for (const a of [34, 30, 22, 18]) L.put(wall, sx * 12, sz * a, sx < 0 ? PI / 2 : -PI / 2);
    L.put(sarc, sx * 26, sz * 28, 0);
    L.put(sarc, sx * 20, sz * 32, PI / 2);
    L.put(brazier, sx * 30, sz * 22, 0);
    L.put(candles, sx * 17, sz * 34.5, 0);
    L.put(candles, sx * 34.5, sz * 25, PI / 2);
  }
  // columns down the nave and at the chamber mouths
  for (const [x, z] of [[-4, -28], [4, -28], [-4, 28], [4, 28], [-4, -12], [4, -12], [-4, 12], [4, 12], [-16, 0], [16, 0], [-28, -8], [28, -8], [-28, 8], [28, 8]]) L.put(column, x, z, 0);
  // braziers in the nave and candles along the walls between the gaps
  for (const [x, z] of [[-9, -6], [9, 6], [-9, 6], [9, -6], [0, -24], [0, 24]]) L.put(brazier, x, z, 0);
  for (const [x, z, yaw] of [[-20, -W + 1.2, 0], [20, -W + 1.2, 0], [-20, W - 1.2, PI], [20, W - 1.2, PI], [-W + 1.2, 0, PI / 2], [W - 1.2, 0, -PI / 2]]) L.put(candles, x, z, yaw);
  // bone piles and oil urns
  const busy = (x, z, rad) => L.at.some((a) => a.solid && Math.abs(x - a.x) < a.hx + rad && Math.abs(z - a.z) < a.hz + rad);
  let np = 0, nu = 0, tries = 0;
  while ((np < 20 || nu < 10) && tries++ < 5000) {
    const x = (r() - 0.5) * 2 * (HALF - 3), z = (r() - 0.5) * 2 * (HALF - 3);
    if (Math.hypot(x, z) < 7 || busy(x, z, 1.8)) continue;
    if (np < 20) { L.put(pile, x, z, r() * 2 * PI); np++; } else { L.put(urn, x, z, r() * 2 * PI); nu++; }
  }
  // the light: every brazier a warm pool, the candles small ones, a dim blue fill from above (the scene's key)
  for (const a of L.at.filter((q) => q.name === brazier)) L.light('omni', [a.x, 1.6, a.z], [0, 0, 0], [1.0, 0.55, 0.22], 420, 16, 0, 0, 1);
  for (const a of L.at.filter((q) => q.name === candles)) L.light('omni', [a.x, 1.3, a.z], [0, 0, 0], [1.0, 0.7, 0.38], 90, 8, 0, 0, 1);
  L.pickups = [[-34, -34], [34, -34], [-34, 34], [34, 34], [0, -20], [0, 20], [-30, 0], [30, 0], [-22, -16], [22, 16]];
  L.scene = {
    title: 'The Ossuary', keyNote: 'a dim cold fill from high above; the braziers and candles (baked) are the real light',
    sun: { dir: [-8, 30, 14], color: [0.45, 0.55, 0.85], energy: 0.55, fog: 0.6 },
    rim: { dir: [20, 6, -24], color: [1.0, 0.62, 0.3], energy: 0.9 },
    bg: [0.008, 0.008, 0.012], ambient: [0.3, 0.33, 0.45], ambientEnergy: 0.16, sky: [0.25, 0.28, 0.4], ground: [0.06, 0.05, 0.04], hemi: 0.25,
    fog: [0.07, 0.05, 0.035], fogDensity: 0.012, exposure: 1.3, bloom: 0.2, vignette: 0.5,
  };
  return L;
}

const LEVELS = { sluice, ossuary };
const want = process.argv.slice(2);
mkdirSync(A('levels'), { recursive: true });
for (const [id, make] of Object.entries(LEVELS)) {
  if (want.length && !want.includes(id)) continue;
  const L = make();
  writeFileSync(A(`levels/${id}.cwlevel`), L.text());
  writeFileSync(A(`scenes/${id}.cwscene`), scene(id, L.scene));
  console.log(`${id}: ${L.props.length} props, ${L.at.length} placements (${L.at.filter((a) => a.solid).length} solid), ${L.lights.length} lights, ${L.hazards.length} hazards`);
}
