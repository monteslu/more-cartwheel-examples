// The descent's colour grades (LEVELS.md): a 3D LUT (.cube) per level, the yard's recipe (tools/gen-lut.mjs:
// an S-curve, a tint split between shadows and highlights, saturation) with each level's own numbers.
// All generated here.
//   node tools/gen-level-luts.mjs [out dir (default assets/grade)] [level ...]
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

// contrast, shadow tint (added at the darkest), highlight tint (added at the brightest), saturation,
// black lift (a floor under the shadows, as a colour)
const GRADES = {
  sluice: { contrast: 0.5, shadow: [-0.03, 0.025, 0.035], high: [0.015, 0.03, -0.01], sat: 0.9, lift: [0.0, 0.006, 0.008] },   // crushed toward teal
  ossuary: { contrast: 0.55, shadow: [-0.02, -0.005, 0.04], high: [0.06, 0.03, -0.05], sat: 1.05, lift: [0.002, 0.002, 0.008] }, // warm mids, blue-black shadows
  foundry: { contrast: 0.55, shadow: [-0.02, 0.0, 0.04], high: [0.07, 0.02, -0.06], sat: 1.1, lift: [0.004, 0.003, 0.006] },
  grotto: { contrast: 0.45, shadow: [0.03, -0.02, 0.05], high: [-0.03, 0.04, 0.03], sat: 1.1, lift: [0.006, 0.0, 0.01] },
  cathedral: { contrast: 0.6, shadow: [0.0, -0.01, 0.03], high: [0.07, -0.01, -0.02], sat: 1.05, lift: [0.006, 0.0, 0.004] },
  rift: { contrast: 0.6, shadow: [0.02, -0.01, 0.05], high: [-0.03, 0.03, 0.05], sat: 0.85, lift: [0.0, 0.0, 0.006] },
  core: { contrast: 0.6, shadow: [-0.02, 0.02, -0.01], high: [0.08, 0.02, -0.06], sat: 1.15, lift: [0.008, 0.0, 0.0] },
};

const args = process.argv.slice(2);
const out = resolve(args[0] && !GRADES[args[0]] ? args.shift() : 'assets/grade');
const N = 17;
const sc = (x) => { const y = Math.min(1, Math.max(0, x)); return y * y * (3 - 2 * y); };
const clamp = (x) => Math.min(1, Math.max(0, x));
mkdirSync(out, { recursive: true });
for (const [name, g] of Object.entries(GRADES)) {
  if (args.length && !args.includes(name)) continue;
  const lines = [`# hordeshooter ${name} grade (generated by tools/gen-level-luts.mjs)`, `TITLE "${name}"`, `LUT_3D_SIZE ${N}`, 'DOMAIN_MIN 0 0 0', 'DOMAIN_MAX 1 1 1'];
  for (let b = 0; b < N; b++) for (let gg = 0; gg < N; gg++) for (let r = 0; r < N; r++) {
    let c = [r / (N - 1), gg / (N - 1), b / (N - 1)];
    c = c.map((x) => x + (sc(x) - x) * g.contrast);
    const L = 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
    const sh = Math.pow(1 - L, 2), hi = L * L;
    c = c.map((x, k) => x + g.shadow[k] * sh + g.high[k] * hi + g.lift[k] * (1 - x));
    c = c.map((x) => L + (x - L) * g.sat);
    lines.push(c.map((x) => clamp(x).toFixed(5)).join(' '));
  }
  writeFileSync(resolve(out, `${name}.cube`), lines.join('\n') + '\n');
  console.log('wrote', resolve(out, `${name}.cube`));
}
