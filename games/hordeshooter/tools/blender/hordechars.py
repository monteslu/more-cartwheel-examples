# Builds the horde's characters and bakes their animation, headless:
#   flatpak run org.blender.Blender --background --factory-startup --python \
#     <abs>/tools/blender/hordechars.py -- <abs out dir> [kind ...] [--sheet <abs png dir>]
# kinds: soldier runner brute bloater boss (default all).
#
# Each character is modelled from primitives (bmesh), skinned to an armature
# with hand-set weights, posed per frame by a procedural cycle, and evaluated
# through Blender's own armature modifier. The result is written as a .cwchar
# file: the topology once (UVs, baked ambient occlusion colours, triangles) and
# a position+normal set per animation frame. The game draws one instanced mesh
# per frame of the cycle, so thousands of animated characters stay one draw per
# frame bucket. Every shape here is generated by this script (no outside art).
#
# Format (little endian): "CWCH", u32 version(1), u32 clips, u32 groups
#   per clip:  u32 frames
#   per group: u32 verts, u32 tris, f32 uv[2*verts], f32 colour[3*verts],
#              u16 index[3*tris] (padded to a multiple of 4 bytes),
#              then for each clip frame in order: f32 pos[3*verts], f32 nrm[3*verts]
# Axes in the file: Y up, the character faces +Z (glTF convention).
import sys, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
