def sheet(name, ob, ao, poses):
    """a quick contact sheet of the first clip: Cycles on the CPU, tiny"""
    if not SHEET: return
    os.makedirs(SHEET, exist_ok=True)
    sc = bpy.context.scene
    sc.render.engine = 'CYCLES'
    sc.cycles.device = 'CPU'; sc.cycles.samples = 8
    sc.render.resolution_x = 360; sc.render.resolution_y = 360
    cam = bpy.data.objects.new("cam", bpy.data.cameras.new("cam"))
    sc.collection.objects.link(cam); sc.camera = cam
    sun = bpy.data.objects.new("sun", bpy.data.lights.new("sun", 'SUN')); sun.data.energy = 3
    sun.rotation_euler = (0.9, 0.2, 0.6); sc.collection.objects.link(sun)
    w = bpy.data.worlds.new("w"); w.use_nodes = True
    w.node_tree.nodes["Background"].inputs[0].default_value = (0.3, 0.32, 0.36, 1); sc.world = w
    mat = bpy.data.materials.new("m"); mat.use_nodes = True
    bsdf = next(n for n in mat.node_tree.nodes if n.type == "BSDF_PRINCIPLED")
    bsdf.inputs["Roughness"].default_value = 0.6
    ob.data.materials.append(mat)
    bb = [ob.matrix_world @ Vector(c) for c in ob.bound_box]
    H = max(v.z for v in bb)
    n = len(poses[0])
    for fi in range(0, n, max(1, n // 4)):
        pose_frame(ao, poses[0][fi])
        for ang, tag in ((0.8, "q"), (math.pi * 0.5, "s")):
            cam.location = (math.sin(ang) * -H * 2.3, math.cos(ang) * -H * 2.3, H * 0.7)
            d = Vector((0, 0, H * 0.45)) - cam.location
            cam.rotation_euler = d.to_track_quat('-Z', 'Y').to_euler()
            cam.data.lens = 50
            sc.render.filepath = os.path.join(SHEET, "%s_%02d%s.png" % (name, fi, tag))
            bpy.ops.render.render(write_still=True)

