// Writes the dusk grade: a 3D colour LUT (.cube) with a gentle S-curve, teal in the
// shadows, warm in the highlights and a touch more saturation. All generated here.
//   node tools/gen-lut.mjs assets/grade/dusk.cube
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const out = resolve(process.argv[2] || 'assets/grade/dusk.cube');
const N = 17;
const lines = ['# hordeshooter dusk grade (generated by tools/gen-lut.mjs)', 'TITLE "dusk"', `LUT_3D_SIZE ${N}`, 'DOMAIN_MIN 0 0 0', 'DOMAIN_MAX 1 1 1'];
const sc = (x) => { const y = Math.min(1, Math.max(0, x)); return y * y * (3 - 2 * y); };
const clamp = (x) => Math.min(1, Math.max(0, x));
for (let b = 0; b < N; b++) for (let g = 0; g < N; g++) for (let r = 0; r < N; r++) {
  let c = [r / (N - 1), g / (N - 1), b / (N - 1)];
  c = c.map((x) => x + (sc(x) - x) * 0.45);          // contrast
  const L = 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
  const sh = Math.pow(1 - L, 2), hi = L * L;
  c = [c[0] - 0.025 * sh + 0.05 * hi, c[1] + 0.012 * sh + 0.012 * hi, c[2] + 0.045 * sh - 0.045 * hi]; // teal shadows, warm lights
  c = c.map((x) => L + (x - L) * 1.12);               // saturation
  lines.push(c.map((x) => clamp(x).toFixed(5)).join(' '));
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n') + '\n');
console.log('wrote', out);
